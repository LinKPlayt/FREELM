function stamp(ctx, style, spr, cx, cy, scale, rot, a) {
  if (style === "neon") {
    const glow = tint(spr, rgba(a)); ctx.save(); ctx.shadowColor = rgba(a); ctx.shadowBlur = 50; place(ctx, glow, cx, cy, scale, rot, 0.9); ctx.restore();
    place(ctx, outline(spr, "rgb(255,255,255)", 6), cx, cy, scale, rot); place(ctx, spr, cx, cy, scale, rot);
  } else if (style === "paper") {
    place(ctx, tint(spr, "rgba(60,40,20,0.35)"), cx + 18 * scale, cy + 24 * scale, scale, rot);
    place(ctx, outline(spr, "rgb(255,252,244)", 14), cx, cy, scale, rot); place(ctx, spr, cx, cy, scale, rot);
  } else if (style === "blueprint") {
    place(ctx, outline(spr, "rgb(235,245,255)", 5), cx, cy, scale, rot); place(ctx, tint(spr, "rgb(16,58,112)"), cx, cy, scale, rot);
    place(ctx, tint(spr, "rgba(235,245,255,0.18)"), cx, cy, scale, rot);
  } else if (style === "pop") {
    place(ctx, tint(spr, INK), cx + 16 * scale, cy + 16 * scale, scale, rot);
    place(ctx, outline(spr, INK, 12), cx, cy, scale, rot); place(ctx, spr, cx, cy, scale, rot);
  } else {
    place(ctx, spr, cx, cy + 10, scale * 1.0, rot);
  }
}

// spec: { motifs: [...], style, accent: [r,g,b], seed }
export function drawArt(ctx, { motifs = ["coins"], style = "flat", accent = [255, 214, 10], seed = "" }) {
  const r = rng(style + motifs.join() + seed);
  ctx.save();
  (BACKGROUNDS[style] || BACKGROUNDS.flat)(ctx, accent, r);
  // Two supporting subjects, smaller, up and to the sides; the main subject big in the middle.
  const side = motifs.slice(1, 3);
  if (side.length < 2) side.push(...["coins", "chartUp", "bulb", "target"].filter((m) => !motifs.includes(m)).slice(0, 2 - side.length));
  [[230, 470, -0.18], [860, 560, 0.16]].forEach(([x, y, rot], k) => stamp(ctx, style, sprite(side[k], accent), x, y, 0.55 + r() * 0.08, rot, accent));
  stamp(ctx, style, sprite(motifs[0], accent), W / 2, 830, 1.32, (r() - 0.5) * 0.12, accent);
  // A little life around it: sparkles (flat, neon), confetti dots (paper, pop), plus-marks (blueprint).
  for (let i = 0; i < 14; i++) {
    const x = 80 + r() * (W - 160), y = 300 + r() * 1100;
    if (Math.hypot(x - W / 2, y - 830) < 360) continue;
    if (style === "blueprint") { line(ctx, [[x - 12, y], [x + 12, y]], 3, "rgba(255,255,255,0.6)"); line(ctx, [[x, y - 12], [x, y + 12]], 3, "rgba(255,255,255,0.6)"); }
    else if (style === "paper" || style === "pop") circle(ctx, x, y, 8 + r() * 10, i % 3 ? rgba(accent, 0.8) : (style === "pop" ? INK : "rgba(60,40,20,0.35)"));
    else { ctx.save(); ctx.translate(x, y); ctx.rotate(Math.PI / 4); const s = 6 + r() * 12; poly(ctx, [[0, -s * 2], [s / 2, -s / 2], [s * 2, 0], [s / 2, s / 2], [0, s * 2], [-s / 2, s / 2], [-s * 2, 0], [-s / 2, -s / 2]], style === "neon" ? rgba(lighten(accent, 0.4), 0.9) : "rgba(255,255,255,0.6)"); ctx.restore(); }
  }
  ctx.restore();
}

/* ---------------------------------------------------------------- saved illustrations */
export const ART_CACHE = "reelbot-user-art", ART_PATH = "/user/art/";
const INDEX = "artIndex", KEEP = 150;
const hex = (c) => c.map((v) => v.toString(16).padStart(2, "0")).join("");
export const artKey = ({ motifs, style, accent }) => `${style}-${motifs.join("_")}-${hex(accent)}`;
function index() { try { return JSON.parse(localStorage.getItem(INDEX) || "[]"); } catch { return []; } }
function saveIndex(list) { try { localStorage.setItem(INDEX, JSON.stringify(list.slice(-KEEP))); } catch { /* full or private */ } }
export const savedArt = () => index();
export function forgetArt() { saveIndex([]); }

// The illustration for a spec: the saved one if this idea was drawn before, else drawn now and saved.
export async function artFor(spec, topic = "") {
  const key = artKey(spec), url = new URL(ART_PATH + key + ".jpg", location.href).href;
  let cache = null;
  try { cache = await caches.open(ART_CACHE); } catch { /* no Cache Storage (private mode) */ }
  const hit = cache && (await cache.match(url).catch(() => null));
  if (hit) {
    try {
      const bmp = await createImageBitmap(await hit.blob());
      saveIndex([...index().filter((e) => e.key !== key), { ...(index().find((e) => e.key === key) || { key, motifs: spec.motifs, style: spec.style }), used: Date.now(), uses: ((index().find((e) => e.key === key) || {}).uses || 0) + 1 }]);
      return { bitmap: bmp, reused: true };
    } catch { /* drawn again below */ }
  }
  const c = canvas(W, H);
  drawArt(c.getContext("2d"), { ...spec, seed: key });
  const blob = await new Promise((res) => (c.toBlob ? c.toBlob(res, "image/jpeg", 0.86) : res(null)));
  const bitmap = await createImageBitmap(c);
  c.width = c.height = 0;
  if (cache && blob) {
    try {
      await cache.put(url, new Response(blob, { headers: { "content-type": "image/jpeg" } }));
      const list = index().filter((e) => e.key !== key);
      list.push({ key, motifs: spec.motifs, style: spec.style, topic: String(topic).slice(0, 60), made: Date.now(), used: Date.now(), uses: 1 });
      // Keep the most recently used ones; drop the oldest from the phone.
      if (list.length > KEEP) { list.sort((a, b) => a.used - b.used); for (const old of list.splice(0, list.length - KEEP)) cache.delete(new URL(ART_PATH + old.key + ".jpg", location.href).href).catch(() => {}); }
      saveIndex(list);
    } catch { /* storage full: the picture is still used in this video */ }
  }
  return { bitmap, reused: false };
}
