// The illustrator: draws a full-screen illustration for what a line is talking about, on the phone,
// in one of several art styles, and keeps it so the same idea looks the same next time.
//
//   conceptsOf(text, topic)  -> ["house", "chartUp", ...]   what to draw (main subject first)
//   drawArt(ctx, spec)       draws a 1080x1920 illustration (sync; used for thumbnails too)
//   artFor(spec)             the illustration as an ImageBitmap: from the saved set if it was drawn
//                            before, otherwise drawn now and saved (Cache Storage, kept across updates)
//
// Nothing is downloaded and nothing is generated by a model: every picture is drawn from vector parts,
// so it's free, offline and instant.

